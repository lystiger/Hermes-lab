    # Rule 7: A batch with one phase behaves exactly like a sequential phase
    # -------------------------------------------------------------------------

    def test_rule7_single_phase_batch_behaves_like_sequential_phase(self):
        """Rule 7: A batch with one phase behaves exactly like a sequential phase."""
        with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as temp_dir:
            root = Path(temp_dir)
            self.init_target_repo(root / "repo")

            phase_p1 = self.make_phase("p1", parallel_group="grp-batch", owned_paths=["p1/"])
            phase_p2 = self.make_phase("p2", parallel_group="grp-batch", owned_paths=["p2/"])
            # Single-phase batch with unique parallel_group
            phase_solo = self.make_phase("solo", parallel_group="grp-solo", owned_paths=["solo/"])
            spec_file = self.write_spec(root / "spec.json", [phase_p1, phase_p2, phase_solo])

            barrier_batch = threading.Barrier(2, timeout=10.0)
            active_now = 0
            solo_concurrency = None
            active_lock = threading.Lock()

            def fake_exec(context):
                nonlocal active_now, solo_concurrency
                name = context.phase["name"]
                with active_lock:
                    active_now += 1

                if name in ("p1", "p2"):
                    try:
                        barrier_batch.wait(timeout=10.0)
                    except threading.BrokenBarrierError as err:
                        raise SprintRunnerError("FAILED_TIMEOUT", f"Batch barrier timed out: {err}") from err
                else:
                    with active_lock:
                        solo_concurrency = active_now

                handoff = context.worktree / context.phase["expected_handoff"]
                handoff.write_text("OK\n", encoding="utf-8")
                target = context.worktree / context.phase["owned_paths"][0].rstrip("/") / f"{name}.py"
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(f"# {name}\n", encoding="utf-8")

                with active_lock:
                    active_now -= 1

                return SimpleNamespace(stdout="", stderr="", returncode=0, runtime_metadata={})

            runner = self.create_runner(spec_file, FakeAgentAdapter(fake_exec))
            success = runner.execute()

            self.assertTrue(success, f"Sprint failed: {runner.run_summary.get('status')}")
            # Solo batch ran strictly with concurrency 1
            self.assertEqual(solo_concurrency, 1)

            # Solo phase integrated properly
            phase_summaries = runner.run_summary["phases"]
            self.assertEqual(len(phase_summaries), 3)
            self.assertTrue(phase_summaries[2]["integrated"])
            self.assertEqual(phase_summaries[2]["status"], "SUCCESS")

            # Solo commit is on top of integration branch
            res = subprocess.run(
                ["git", "log", "-n", "1", "--format=%s", "s08/integration"],
                cwd=root / "repo",
                check=True,
                capture_output=True,
                text=True,
            )
            self.assertIn("solo", res.stdout)

