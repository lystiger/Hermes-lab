    def test_rule4_commits_and_merges_occur_one_at_a_time_in_spec_order(self):
        """Rule 4: Commits and merges into integration worktree happen one phase at a time, in spec order."""
        with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as temp_dir:
            root = Path(temp_dir)
            self.init_target_repo(root / "repo")

            phase_first = self.make_phase("first-phase", parallel_group="order-group", owned_paths=["pkg_a/"])
            phase_second = self.make_phase("second-phase", parallel_group="order-group", owned_paths=["pkg_b/"])
            spec_file = self.write_spec(root / "spec.json", [phase_first, phase_second])

            barrier = threading.Barrier(2, timeout=10.0)
            merge_calls = []

            def fake_exec(context):
                name = context.phase["name"]
                try:
                    barrier.wait(timeout=10.0)
                except threading.BrokenBarrierError as err:
                    raise SprintRunnerError("FAILED_TIMEOUT", f"Barrier timed out: {err}") from err

                # Even if second-phase finishes its agent work faster:
                if name == "first-phase":
                    time.sleep(0.05)

                handoff = context.worktree / context.phase["expected_handoff"]
                handoff.write_text("OK\n", encoding="utf-8")
                target = context.worktree / context.phase["owned_paths"][0].rstrip("/") / f"{name}.py"
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(f"# {name}\n", encoding="utf-8")
                return SimpleNamespace(stdout="", stderr="", returncode=0, runtime_metadata={})

            runner = self.create_runner(spec_file, FakeAgentAdapter(fake_exec))

            orig_run_cmd = runner.run_cmd

            def tracked_run_cmd(cmd, *args, **kwargs):
                if isinstance(cmd, list) and len(cmd) >= 2 and cmd[0] == "git" and cmd[1] == "merge":
                    cwd = kwargs.get("cwd") or (args[0] if args else None)
                    if cwd and Path(cwd).name == "integration":
                        merge_calls.append(list(cmd))
                return orig_run_cmd(cmd, *args, **kwargs)

            runner.run_cmd = tracked_run_cmd
            success = runner.execute()

            self.assertTrue(success, f"Sprint failed: {runner.run_summary.get('status')}")
            self.assertEqual(len(merge_calls), 2, "Expected exactly 2 integration merges")
            self.assertIn("first-phase", str(merge_calls[0]))
            self.assertIn("second-phase", str(merge_calls[1]))

            # In integration branch history, first-phase must be ancestor of second-phase merge
            res = subprocess.run(
                ["git", "log", "--format=%s", "s08/integration"],
                cwd=root / "repo",
                check=True,
                capture_output=True,
                text=True,
            )
            commit_messages = res.stdout.strip().splitlines()
            second_merge_idx = next(i for i, msg in enumerate(commit_messages) if "second-phase" in msg)
            first_merge_idx = next(i for i, msg in enumerate(commit_messages) if "first-phase" in msg)
            self.assertLess(second_merge_idx, first_merge_idx, "first-phase must be merged before second-phase")

    def test_rule4_no_merges_during_concurrent_agent_execution(self):
        """Rule 4: While agents are executing concurrently, no commits or merges exist in integration."""
        with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as temp_dir:
            root = Path(temp_dir)
            self.init_target_repo(root / "repo")

            phase_a = self.make_phase("phase-a", parallel_group="grp-merge", owned_paths=["srv_a/"])
            phase_b = self.make_phase("phase-b", parallel_group="grp-merge", owned_paths=["srv_b/"])
            spec_file = self.write_spec(root / "spec.json", [phase_a, phase_b])

            barrier = threading.Barrier(2, timeout=10.0)
            integration_heads_during_exec = []

            def fake_exec(context):
                try:
                    barrier.wait(timeout=10.0)
                except threading.BrokenBarrierError as err:
                    raise SprintRunnerError("FAILED_TIMEOUT", f"Barrier timed out: {err}") from err

                integration_dir = context.runner.worktree_root / "integration"
                res = subprocess.run(
                    ["git", "rev-parse", "HEAD"],
                    cwd=integration_dir,
                    check=True,
                    capture_output=True,
                    text=True,
                )
                integration_heads_during_exec.append(res.stdout.strip())

                handoff = context.worktree / context.phase["expected_handoff"]
                handoff.write_text("OK\n", encoding="utf-8")
                target = context.worktree / context.phase["owned_paths"][0].rstrip("/") / "f.py"
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text("ok = True\n", encoding="utf-8")
                return SimpleNamespace(stdout="", stderr="", returncode=0, runtime_metadata={})

            runner = self.create_runner(spec_file, FakeAgentAdapter(fake_exec))
            success = runner.execute()

            self.assertTrue(success)
            res_base = subprocess.run(
                ["git", "rev-parse", "main"],
                cwd=root / "repo",
                check=True,
                capture_output=True,
                text=True,
            )
            base_sha = res_base.stdout.strip()
            for head_sha in integration_heads_during_exec:
                self.assertEqual(
                    head_sha,
                    base_sha,
                    "Integration worktree had commits/merges while agents were still running!",
                )

    # -------------------------------------------------------------------------
    # Rule 5: Batch failure halts merge for all phases; finished phases not merged
    # -------------------------------------------------------------------------

    def test_rule5_batch_failure_prevents_merge_of_all_phases_in_batch(self):
        """Rule 5: If any phase in a batch fails, no phase in that batch is merged."""
        with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as temp_dir:
            root = Path(temp_dir)
            self.init_target_repo(root / "repo")

            phase_ok = self.make_phase("phase-ok", parallel_group="fail-group", owned_paths=["app_ok/"])
            phase_bad = self.make_phase("phase-bad", parallel_group="fail-group", owned_paths=["app_bad/"])
            spec_file = self.write_spec(root / "spec.json", [phase_ok, phase_bad])

            barrier = threading.Barrier(2, timeout=10.0)

